"""Assemble Docs/MoE_Application_Documentation.html (single self-contained file).

Usage:  .venv/bin/python -m docs_tools.build_docs

Two passes: pass 1 collects figure numbers and section titles, pass 2 renders in strict mode so every
cross-reference must resolve. Images are embedded as base64 JPEG; the full PNGs stay in Docs/assets/.
"""
from __future__ import annotations

import sys
from datetime import datetime
from html import escape

from . import data
from .chapters_core import chapter1, chapter2, chapter3, chapter4
from .chapters_ops import chapter5, chapter6, chapter7, chapter8
from .context import CHAPTERS, Ctx, legend_key
from .theme import CSS

OUT = data.DOCS / "MoE_Application_Documentation.html"
RENDERERS = [chapter1, chapter2, chapter3, chapter4, chapter5, chapter6, chapter7, chapter8]


def render_chapters(ctx: Ctx) -> list[str]:
    return [fn(ctx) for fn in RENDERERS]


def build_toc(ctx: Ctx) -> str:
    items = []
    for n, title in CHAPTERS:
        items.append(f'<li><a href="#ch{n}"><span class="num">{n}</span>{escape(title)}</a></li>')
        for c, anchor, t in ctx.sections:
            if c == n:
                items.append(f'<li class="sec"><a href="#{anchor}">{escape(t)}</a></li>')
    return "\n".join(items)


def cover(bench: dict, n_tests: int, total_lines: int) -> str:
    host = bench["host"]
    meta = [("Model", host["model"]), ("Host", f"{host['cpu']} · {host['ram_gb']} GB"),
            ("Ollama", f"{host['ollama_version']} · {host['runner']} runner"),
            ("Application", f"{total_lines} lines · {n_tests} tests"), ("Benchmark", bench["generated_at"][:10]),
            ("Licence", "MIT (app) · NVIDIA Open Model Agreement (model)")]
    cells = "".join(f"<div><b>{escape(k)}</b>{escape(v)}</div>" for k, v in meta)
    return (f'<section class="cover" id="top"><div class="kicker">Technical documentation</div>'
            f'<h1>Nemotron 3.5 Lightning · Mixture-of-Experts Explorer</h1>'
            f'<div class="tag">A local, Ollama-powered Streamlit application that makes sparse expert routing visible, '
            f'with measured inference metrics.</div><div class="meta">{cells}</div>'
            f'<a class="btn" href="#toc">Contents ↓</a></section>')


def pager(i: int) -> str:
    prev = (f'<a href="#ch{CHAPTERS[i - 1][0]}">← {CHAPTERS[i - 1][0]}. {escape(CHAPTERS[i - 1][1])}</a>'
            if i > 0 else "<span></span>")
    nxt = (f'<a href="#ch{CHAPTERS[i + 1][0]}">{CHAPTERS[i + 1][0]}. {escape(CHAPTERS[i + 1][1])} →</a>'
           if i < len(CHAPTERS) - 1 else '<a href="#top">↑ Back to top</a>')
    return f'<div class="pager">{prev}{nxt}</div>'


def figure_index(ctx: Ctx) -> str:
    rows = "".join(f'<tr><td><a href="#{fid}">{escape(lab)}</a></td><td>{escape(ctx.captions.get(fid, ""))}</td></tr>'
                   for fid, lab in ctx.new_labels.items())
    return f'<details><summary>List of figures ({len(ctx.new_labels)})</summary><table><tbody>{rows}</tbody></table></details>'


def build(strict: bool = True) -> tuple[str, Ctx]:
    first = Ctx()
    render_chapters(first)                         # pass 1: labels + section titles
    titles = {a: t for _, a, t in first.sections}
    ctx = Ctx(first.new_labels, strict=strict, titles=titles)
    bodies = render_chapters(ctx)                  # pass 2: strict
    bench = data.load_benchmark()
    n_tests = sum(data.count_tests().values())
    total_lines = sum(data.source_stats().values())
    chapters_html = "\n".join(f'<section class="chap">{b}{pager(i)}</section>' for i, b in enumerate(bodies))
    side = (f'<nav class="side"><div class="brand">MoE Explorer</div>'
            f'<div class="sub">Documentation · {datetime.now():%Y-%m-%d}</div><ol>{build_toc(ctx)}</ol></nav>')
    intro = ('<section id="toc"><h2 class="chapter" style="border:0;margin-top:0">Contents</h2>'
             '<p class="lead">Eight chapters; every screenshot is a capture of the running application, every number a '
             'measurement or a value read from the code at build time.</p>'
             f'<h4>How to read the figures</h4>{legend_key()}{figure_index(ctx)}</section>')
    foot = ('<footer>Made with IBM Bob · generated by <code>docs_tools/build_docs.py</code> · '
            f'{datetime.now():%Y-%m-%d %H:%M}</footer>')
    html = ('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            '<title>Nemotron 3.5 Lightning · MoE Explorer: Documentation</title>'
            f'<style>{CSS}</style></head><body><div class="layout">{side}'
            f'<main>{cover(bench, n_tests, total_lines)}{intro}{chapters_html}{foot}</main></div></body></html>')
    return html, ctx


def main(argv: list[str] | None = None) -> int:
    html, ctx = build()
    OUT.write_text(html, encoding="utf-8")
    print(f"written {OUT} ({len(html) / 1e6:.2f} MB, {len(ctx.new_labels)} figures, {len(ctx.sections)} sections)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
